#!/usr/bin/env node
// ─────────────────────────────────────────────────────────────────────────────
// power-list-gaps.mjs (test) — fixtures for scripts/power-list-gaps.mjs (F-487).
//
// Covers: Power List rule ids collected from the program docs on disk by the
// source's `ruleId` (the collection id only as a fallback on a legacy doc that
// carries none — and NEVER when the two differ), deduped across programs,
// classified against the rules domain's inventory (documented / already
// queued / missing), the work list keyed by the rules domain's RECORDED
// idField in the `upsert-batch --file` shape and sorted by id, stubs and
// non-Power-List sources ignored, the lane folders resolved from the
// manifest's recordings, and the failure-honesty contract: a missing
// argument or an unreadable manifest refuses loudly with exit 1 naming the
// script; a missing journey folder is said (journeyDirMissing) with an empty
// list, never silently.
//
// Fixtures use the fictional acme tenant, under the OS temp dir (shared rig).
//
// Run:  node plugins/gs-superadmin/test/power-list-gaps.mjs
// Zero dependencies — Node built-ins only.
// ─────────────────────────────────────────────────────────────────────────────
import { readFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { makeTempDir, removeTempDir, writeFiles, runNode } from "../../../test/rig.mjs";

const SCRIPT = join(dirname(fileURLToPath(import.meta.url)), "..", "scripts", "power-list-gaps.mjs");

let failures = 0;
function check(label, cond, detail) {
  console.log(`${cond ? "PASS" : "FAIL"}  ${label}`);
  if (!cond) {
    failures++;
    console.log(`      ${JSON.stringify(detail)?.slice(0, 600)}`);
  }
}

// A compact program doc with the given sources (the describe-batch program
// doc shape: H1 + bullets + one fenced payload).
const programDoc = (id, name, sources, { stub = false } = {}) =>
  [
    `# ${name}`, "",
    stub ? "> Metadata-only stub — generated by manifest.mjs stub" : "> Compacted program doc — generated by describe-batch.mjs",
    "", `- key: journey/${id}`, `- id: ${id}`, `- name: ${name}`, "",
    ...(stub ? [] : ["```json", JSON.stringify({ result: true, data: { advancedOutreach: {
      advancedOutreachId: id, advancedOutreachName: name, advancedOutreachStatus: ["PROCESSING"],
      advancedOutreachModel: "DRIPV2", stepJson: "[]", participantSourceConfigurations: sources,
    } } }), "```", ""]),
  ].join("\n");
const qb = (cfg, name, collectionId, ruleId) => ({
  participantSourceConfigurationId: cfg, participantSourceType: "QUERY_BUILDER", participantSourceName: name,
  participantSourceCollectionId: collectionId, ...(ruleId === undefined ? {} : { ruleId }),
  participantOperationType: "ADD_ALL_PARTICIPANT_IN_POWER_LIST",
});

const manifest = {
  slug: "acme-prod",
  baseUrl: "https://acme.gainsightcloud.com",
  domains_indexed: {
    journey: { idField: "advancedOutreachId", listCommand: "gs-admin --json jo p list" },
    "rules-engine": { idField: "ruleId", listCommand: "gs-admin --json re r list", describeCommand: "gs-admin --json re r describe --id {id}" },
  },
  inventory: {
    "journey/prog-a": { domain: "journey", id: "prog-a", depth: "full", status: "documented" },
    "journey/prog-b": { domain: "journey", id: "prog-b", depth: "full", status: "documented" },
    "journey/prog-c": { domain: "journey", id: "prog-c", depth: "full", status: "documented" },
    "journey/prog-d": { domain: "journey", id: "prog-d", depth: "full", status: "documented" },
    "journey/prog-legacy": { domain: "journey", id: "prog-legacy", depth: "full", status: "documented" },
    "journey/prog-stub": { domain: "journey", id: "prog-stub", depth: "metadata", status: "documented" },
    "rules-engine/pl-documented": { domain: "rules-engine", id: "pl-documented", depth: "full", status: "documented" },
    // documented in the manifest, but its doc is GONE from disk (F-487 reopen, instance 4): re-documented, not trusted
    "rules-engine/pl-gone": { domain: "rules-engine", id: "pl-gone", depth: "full", status: "documented" },
    "rules-engine/pl-queued": { domain: "rules-engine", id: "pl-queued", status: "pending" },
    "rules-engine/rule-bionic-1": { domain: "rules-engine", id: "rule-bionic-1", depth: "full", status: "documented" },
  },
};

const ROOT = makeTempDir("power-list-gaps-test");
try {
  writeFiles(ROOT, {
    "acme-prod/_manifest.json": JSON.stringify(manifest),
    // the one documented rule's doc, READABLE as a Power List rule — only this counts as documented
    "acme-prod/rules-engine/pl-documented.md": ["# Acme Renewal Contacts", "", "> Full describe doc — generated by describe-batch.mjs, captured 2026-10-06T00:00:00.000Z.", "", "- key: rules-engine/pl-documented", "- id: pl-documented", "- name: Acme Renewal Contacts", "", "```json",
      JSON.stringify({ result: true, data: { ruleDetails: { ruleId: "pl-documented", ruleName: "Acme Renewal Contacts", ruleType: "ADVANCED_OUTREACH_QUERY_BUILDER" }, taskDetails: [], criteriaDetails: null } }), "```", ""].join("\n"),
    // documented already — not a work item; prog-a also references the gone one
    "acme-prod/journey/prog-a.md": programDoc("prog-a", "Acme Program A", [qb("cfg-a", "Acme Renewal Contacts", "pl-documented", "pl-documented"), qb("cfg-a2", "Acme Gone List", "pl-gone", "pl-gone")]),
    // collection id ≠ rule id: the RULE id is the one that counts
    "acme-prod/journey/prog-b.md": programDoc("prog-b", "Acme Program B", [qb("cfg-b", "Acme Blast Recipients", "pl-coll-stale", "pl-zz-missing")]),
    // a QUERY (dynamic) source and a CSV source: no rule to register
    "acme-prod/journey/prog-c.md": programDoc("prog-c", "Acme Program C", [
      { participantSourceConfigurationId: "cfg-c", participantSourceType: "QUERY", participantSourceName: "Acme Dynamic", participantSourceCollectionId: "coll-q" },
      { participantSourceConfigurationId: "cfg-c2", participantSourceType: "CSV", participantSourceName: "Acme Upload", participantSourceCollectionId: "acme.csv" },
    ]),
    // the same missing rule as prog-b (dedupe) plus one already queued (pending in the manifest)
    "acme-prod/journey/prog-d.md": programDoc("prog-d", "Acme Program D", [qb("cfg-d", "Acme Blast Recipients", "pl-zz-missing", "pl-zz-missing"), qb("cfg-d2", "Acme Queued List", "pl-queued", "pl-queued")]),
    // a legacy doc with no ruleId key at all: the collection id is the fallback
    "acme-prod/journey/prog-legacy.md": programDoc("prog-legacy", "Acme Legacy Program", [qb("cfg-l", "Acme Legacy List", "pl-aa-legacy", undefined)]),
    "acme-prod/journey/prog-stub.md": programDoc("prog-stub", "Acme Stub Program", [], { stub: true }),
  });
  const run = (...args) => runNode(SCRIPT, args, { cwd: ROOT });

  let r = run("acme-prod/_manifest.json");
  const sum = r.status === 0 ? JSON.parse(r.stdout) : null;
  check("runs green and prints one summary JSON line", r.status === 0 && sum !== null, r);
  check("summary: lanes resolved from the recordings (journey, rules-engine) with their basis",
    sum && sum.domains?.journey === "journey" && sum.domains?.rules === "rules-engine" && typeof sum.domainBasis?.rules === "string", { domains: sum?.domains, basis: sum?.domainBasis });
  check("summary: the rules domain's RECORDED idField keys the work list", sum && sum.idField === "ruleId", sum);
  check("summary: programs scanned 5 (full), 1 stub skipped, 6 Power List sources, 5 distinct rules",
    sum && sum.programsScanned === 5 && sum.stubPrograms === 1 && sum.powerListSources === 6 && sum.distinctRules === 5, sum);
  check("summary: 1 documented (doc readable), 1 queued (pending), 1 redoc (documented but doc gone), 2 missing (= written); unreadable = the 4 this run must describe",
    sum && sum.documented === 1 && sum.queued === 1 && sum.redoc === 1 && sum.missing === 2 && sum.written === 2 && sum.unreadable === 4 && sum.journeyDirMissing === false, sum);
  const redocKeys = JSON.parse(readFileSync(join(ROOT, ".gs-superadmin/tmp/pl-gap-redoc.json"), "utf8"));
  check("redoc file: the documented-but-unreadable rule as a manifest key (for `mark --status stale`)", JSON.stringify(redocKeys) === JSON.stringify(["rules-engine/pl-gone"]) && sum.redocFile === ".gs-superadmin/tmp/pl-gap-redoc.json", redocKeys);
  const list = JSON.parse(readFileSync(join(ROOT, ".gs-superadmin/tmp/pl-gap-rules.json"), "utf8"));
  check("work list: the upsert-batch --file shape, keyed by ruleId, sorted by id, named from the source — the RULE id wins over a differing collection id, the collection id is the legacy fallback",
    JSON.stringify(list) === JSON.stringify([
      { ruleId: "pl-aa-legacy", ruleName: "Acme Legacy List" },
      { ruleId: "pl-zz-missing", ruleName: "Acme Blast Recipients" },
    ]), list);
  check("work list: the stale collection id of prog-b is NOT registered", !list.some((x) => x.ruleId === "pl-coll-stale"), list);
  const keys = JSON.parse(readFileSync(join(ROOT, ".gs-superadmin/tmp/pl-gap-keys.json"), "utf8"));
  check("keys file: every rule whose doc is not readable — missing, queued and redoc — as manifest keys under the rules lane (describe-batch --keys-file shape), sorted; the readable documented one excluded",
    JSON.stringify(keys) === JSON.stringify(["rules-engine/pl-aa-legacy", "rules-engine/pl-gone", "rules-engine/pl-queued", "rules-engine/pl-zz-missing"]) && sum.keysFile === ".gs-superadmin/tmp/pl-gap-keys.json", keys);

  // honesty: no journey folder
  writeFiles(ROOT, { "empty-prod/_manifest.json": JSON.stringify({ slug: "empty-prod", baseUrl: "https://acme.gainsightcloud.com", domains_indexed: {}, inventory: {} }) });
  r = run("empty-prod/_manifest.json");
  const sum2 = r.status === 0 ? JSON.parse(r.stdout) : null;
  check("no journey folder: exit 0, journeyDirMissing true, a warning, empty list — said, never silent",
    sum2 && sum2.journeyDirMissing === true && sum2.written === 0 && sum2.warnings.some((w) => /journey\/ folder/.test(w)) &&
      JSON.stringify(JSON.parse(readFileSync(join(ROOT, ".gs-superadmin/tmp/pl-gap-rules.json"), "utf8"))) === "[]", { r, sum2 });

  // honesty: refusals name the script
  r = run();
  check("no argument: exit 1 naming the script", r.status === 1 && /power-list-gaps\.mjs/.test(r.stderr), r.stderr);
  r = run("nope/_manifest.json");
  check("unreadable manifest: exit 1 naming the script and the path", r.status === 1 && /power-list-gaps\.mjs/.test(r.stderr) && /nope/.test(r.stderr), r.stderr);
} finally {
  removeTempDir(ROOT);
}

console.log(failures ? `\n${failures} check(s) FAILED` : "\nall checks passed");
process.exit(failures ? 1 : 0);
