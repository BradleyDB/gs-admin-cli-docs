let failures = 0;
function check(label, cond, detail) {
  console.log(`${cond ? "PASS" : "FAIL"}  ${label}`);
  if (!cond) {
    failures++;
    console.log(`      ${JSON.stringify(detail)}`);
  }
}

function run(args) {
  const res = spawnSync(process.execPath, [BUILD, ...args], { encoding: "utf8" });
  let json = null;
  try { json = JSON.parse(res.stdout); } catch { /* failure path */ }
  return { code: res.status, json, stderr: res.stderr.trim() };
}
function manifest(M, verb, args) {
  const res = spawnSync(process.execPath, [MANIFEST, verb, "--manifest", M, ...args], { encoding: "utf8" });
  if (res.status !== 0) throw new Error(`manifest ${verb} failed: ${res.stderr}`);
  return JSON.parse(res.stdout);
}

