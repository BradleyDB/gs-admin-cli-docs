// One workspace builder so the scenarios can't drift apart.
// rulesDepth: "full" | "metadata" | ["full", "metadata", …] per index
/**
 * @param {string} slug
 * @param {{rulesDepth?: string|string[], withFailedRule?: boolean, chainsFailed?: boolean,
 *          scorecardDepth?: string, journeyDepth?: string, rules?: any}} [opts]
 */
function buildWorkspace(slug, { rulesDepth = "full", withFailedRule = true, chainsFailed = false, scorecardDepth = "full", journeyDepth = "full", rules = RULES } = {}) {
  const M = join(ROOT, slug, "_manifest.json");
  manifest(M, "init", ["--slug", slug, "--base-url", "https://acme--sbx.gainsightcloud.com", "--environment", "sandbox"]);
  let itemsN = 0;
  const items = (rows) => {
    const p = join(ROOT, `${slug}-items-${++itemsN}.json`);
    writeFileSync(p, JSON.stringify({ data: rows }));
    return p;
  };
  const ruleRows = rules.map((r) => ({ ruleId: r.id, name: r.name }));
  if (withFailedRule) ruleRows.push({ ruleId: "rule-acme-0004", name: "CS|Tmp|Broken Rule" });
  manifest(M, "upsert-batch", ["--file", items(ruleRows), "--domain", "rules-engine", "--id-field", "ruleId", "--name-field", "name"]);
  manifest(M, "upsert-batch", ["--file", items([{ workflowId: CHAIN.id, name: CHAIN.name }]), "--domain", "rules-engine-chains", "--id-field", "workflowId", "--name-field", "name"]);
  manifest(M, "upsert-batch", ["--file", items([{ scorecardId: SCORECARD.id, name: SCORECARD.name }]), "--domain", "scorecard", "--id-field", "scorecardId", "--name-field", "name"]);

  const rulesDir = join(ROOT, slug, "rules-engine");
  mkdirSync(rulesDir, { recursive: true });
  rules.forEach((r, i) => {
    const depth = Array.isArray(rulesDepth) ? rulesDepth[i] : rulesDepth;
    if (depth === "full") writeFileSync(join(rulesDir, `${r.id}.md`), doc(`rules-engine/${r.id}`, r.id, r.name, r.payload));
    // metadata stubs carry no describe payload — an empty stub file stands in
    else writeFileSync(join(rulesDir, `${r.id}.md`), `# ${r.name}\n\n> Metadata-only stub.\n\n- key: rules-engine/${r.id}\n- id: ${r.id}\n- name: ${r.name}\n`);
    manifest(M, "mark", ["--key", `rules-engine/${r.id}`, "--status", "documented", "--depth", depth]);
  });
  if (withFailedRule) manifest(M, "mark", ["--key", "rules-engine/rule-acme-0004", "--status", "failed", "--error", "simulated describe failure"]);

  const chainsDir = join(ROOT, slug, "rules-engine-chains");
  mkdirSync(chainsDir, { recursive: true });
  if (chainsFailed) {
    manifest(M, "mark", ["--key", `rules-engine-chains/${CHAIN.id}`, "--status", "failed", "--error", "simulated describe failure"]);
  } else {
    writeFileSync(join(chainsDir, `${CHAIN.id}.md`), doc(`rules-engine-chains/${CHAIN.id}`, CHAIN.id, CHAIN.name, CHAIN.payload));
    manifest(M, "mark", ["--key", `rules-engine-chains/${CHAIN.id}`, "--status", "documented", "--depth", "full"]);
  }

  const scDir = join(ROOT, slug, "scorecard");
  mkdirSync(scDir, { recursive: true });
  if (scorecardDepth === "full") {
    // The `- id:` bullet is written backtick-QUOTED here on purpose (F-341):
    // four domains' KB docs quote it that way, and the committed expected
    // maps below must stay byte-identical — the scorecard-name registry keys
    // on this id, so a reader that stopped unwrapping the span would render
    // every scorecard hint unresolved and fail the byte-for-byte pins.
    writeFileSync(join(scDir, `${SCORECARD.id}.md`), doc(`scorecard/${SCORECARD.id}`, `\`${SCORECARD.id}\``, SCORECARD.name, SCORECARD.payload));
  } else {
    writeFileSync(join(scDir, `${SCORECARD.id}.md`), `# ${SCORECARD.name}\n\n> Metadata-only stub.\n\n- key: scorecard/${SCORECARD.id}\n- id: ${SCORECARD.id}\n- name: ${SCORECARD.name}\n`);
  }
  manifest(M, "mark", ["--key", `scorecard/${SCORECARD.id}`, "--status", "documented", "--depth", scorecardDepth]);

  // journey programs + email-template inventory (program-to-template map).
  // Template entries stay pending on purpose: the map matches inventory ids
  // at any depth — an id needs no doc to identify an edge.
  manifest(M, "upsert-batch", ["--file", items(TEMPLATE_ROWS), "--domain", "journey-email-templates", "--id-field", "templateId", "--name-field", "title"]);
  manifest(M, "upsert-batch", ["--file", items(PROGRAMS.map((p) => ({ programId: p.id, name: p.name }))), "--domain", "journey", "--id-field", "programId", "--name-field", "name"]);
  const joDir = join(ROOT, slug, "journey");
  mkdirSync(joDir, { recursive: true });
  for (const p of PROGRAMS) {
    if (journeyDepth !== "full") {
      // The key bullet is backtick-QUOTED here on purpose (gate-3 F-353): the
      // journey lane used to read it with a raw regex instead of topBullets,
      // so a quoted key missed the inventory lookup, the depth gate was
      // skipped, and this stub was walked as a full program.
      writeFileSync(join(joDir, `${p.id}.md`), `# ${p.name}\n\n> Metadata-only stub.\n\n- key: \`journey/${p.id}\`\n- id: ${p.id}\n- name: ${p.name}\n\n\`\`\`json\n${JSON.stringify({ programId: p.id, name: p.name })}\n\`\`\`\n`);
      manifest(M, "mark", ["--key", `journey/${p.id}`, "--status", "documented", "--depth", "metadata"]);
      continue;
    }
    if (p.corrupt) writeFileSync(join(joDir, `${p.id}.md`), `# ${p.name}\n\n- key: journey/${p.id}\n- id: ${p.id}\n- name: ${p.name}\n\n\`\`\`json\n{ corrupt\n\`\`\`\n`);
    else if (p.compact) writeFileSync(join(joDir, `${p.id}.md`), renderProgramDoc(p.payload, { key: `journey/${p.id}` }).doc);
    else writeFileSync(join(joDir, `${p.id}.md`), doc(`journey/${p.id}`, p.id, p.name, p.payload));
    manifest(M, "mark", ["--key", `journey/${p.id}`, "--status", "documented", "--depth", "full"]);
  }
  return M;
}

